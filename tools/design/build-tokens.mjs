import {readFileSync, writeFileSync} from 'node:fs';
const source = new URL('../../frontend/src/tokens/theme.json', import.meta.url);
const tokens = JSON.parse(readFileSync(source, 'utf8'));
const declarations = [];
function flatten(node, path = []) {
  for (const [key, value] of Object.entries(node)) {
    if (key.startsWith('$')) continue;
    const parts = [...path, key];
    if ('$value' in value) declarations.push(`  --${parts.join('-')}: ${value.$value};`);
    else flatten(value, parts);
  }
}
flatten(tokens);
writeFileSync(new URL('../../frontend/src/tokens/theme.css', import.meta.url), `/* Generated by tools/design/build-tokens.mjs. Edit theme.json. */\n:root {\n${declarations.join('\n')}\n}\n`);
