import {test,expect} from '@playwright/test';
import {setup,command,loginPage,receipt} from './workflow-helpers';

test('administrator has full access; manager keeps operations without accounts or demo',async({page})=>{
 test.setTimeout(90000);
 const f=await setup(page.request);
 const headers={Authorization:'Bearer '+f.manager.token};
 const password=crypto.randomUUID(),login='manager-'+crypto.randomUUID();
 const created=await page.request.post('/api/accounts',{headers,data:{login,password,name:'Операционный менеджер',role:'manager'}});
 expect(created.ok()).toBeTruthy();const manager=await created.json();
 const key=await(await page.request.post('/api/accounts/'+manager.id+'/keys',{headers})).json();
 const limited={Authorization:'Bearer '+key.token};
 for(const path of ['/accounts','/ACCOUNTS','/accounts/'+manager.id+'/keys','/generator','/GENERATOR','/history/generatorEvents'])expect((await page.request.get('/api'+path,{headers:limited})).status(),path).toBe(403);
 for(const path of ['/demo/seed','/DEMO/time','/generator/start','/generator/stop','/accounts'])expect((await page.request.post('/api'+path,{headers:limited,data:{}})).status(),path).toBe(403);
 expect((await page.request.put('/api/accounts/'+manager.id,{headers:limited,data:{login,password,name:'Escalation',role:'admin'}})).status()).toBe(403);
 expect((await page.request.delete('/api/keys/'+key.id,{headers:limited})).status()).toBe(403);
 for(const path of ['/snapshot','/suppliers','/procurement-requests','/delivery-requests','/order-requests'])expect((await page.request.get('/api'+path,{headers:limited})).ok(),path).toBeTruthy();
 await receipt(page.request,f);
 const order=await(await command(page.request,f.waiter.token,'/order-requests',{items:[{dishId:f.dish,portions:1}]})).json();
 expect((await command(page.request,key.token,'/order-requests/'+order.id+'/decision',{expectedVersion:1,decision:'accept'})).status()).toBe(403);
 expect((await command(page.request,f.manager.token,'/order-requests/'+order.id+'/decision',{expectedVersion:1,decision:'accept'})).ok()).toBeTruthy();
 expect((await command(page.request,f.manager.token,'/order-requests/'+order.id+'/serve',{expectedVersion:2})).ok()).toBeTruthy();
 const suppliers=await(await page.request.get('/api/suppliers',{headers:limited})).json();
 expect(suppliers.some((s:any)=>s.id===f.supplier.id)).toBeTruthy();expect(Object.keys(suppliers[0]).sort()).toEqual(['id','name']);
 expect((await command(page.request,key.token,'/procurement-requests',{supplierId:f.supplier.id,items:[{id:'one',productId:f.product,quantity:1,unit:'g'}]})).status()).toBe(201);
 await loginPage(page,login,password,'/accounts');
 await expect(page).toHaveURL(/\/overview$/);
 await expect(page.getByRole('navigation').getByRole('button',{name:'Аккаунты',exact:true})).toHaveCount(0);
 await expect(page.getByRole('navigation').getByRole('button',{name:'Демонстрация',exact:true})).toHaveCount(0);
 await page.goto('/generator');await expect(page).toHaveURL(/\/overview$/);
 await page.getByRole('navigation').getByRole('button',{name:'Заявки поставщикам',exact:true}).click();
 await page.getByText('Создать заявку поставщику',{exact:true}).click();
 await expect(page.getByLabel('Поставщик',{exact:true})).toBeEnabled();
 await loginPage(page,'manager',process.env.FLAGMAN_PASSWORD!,'/accounts');
 await expect(page.getByRole('heading',{name:'Аккаунты и API-ключи',exact:true})).toBeVisible();
 await expect(page.getByRole('navigation').getByRole('button',{name:'Демонстрация',exact:true})).toBeVisible();
 await expect(page.getByLabel('Роль',{exact:true})).toBeVisible();
 expect((await page.request.get('/api/generator',{headers})).ok()).toBeTruthy();
});
